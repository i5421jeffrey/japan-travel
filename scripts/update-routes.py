"""Refresh static road routes, avoiding runtime routing API dependency."""
import concurrent.futures
import json
import pathlib
import subprocess
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parent.parent
script = "const vm=require('node:vm'),fs=require('node:fs');const c={window:{}};vm.runInNewContext(fs.readFileSync('itinerary.js','utf8'),c);console.log(JSON.stringify(c.window.TRIP_DATA.map(d=>d.driving)));"
points = json.loads(subprocess.check_output(['node', '-e', script], cwd=ROOT))


def route(coords):
    waypoints = ';'.join(f'{lng},{lat}' for lat, lng in coords)
    url = f'https://router.project-osrm.org/route/v1/driving/{waypoints}?overview=full&geometries=geojson&steps=false'
    response = subprocess.check_output(['curl', '--fail', '--silent', '--show-error', '--retry', '2', '--max-time', '90', url])
    data = json.loads(response)
    if data.get('code') != 'Ok' or not data.get('routes'):
        raise RuntimeError(f'Route unavailable: {data.get("code")}')
    result = data['routes'][0]
    return {'geometry': result['geometry'], 'duration': result['duration'], 'distance': result['distance'], 'source': 'OSRM / OpenStreetMap', 'retrievedAt': datetime.now(timezone.utc).isoformat()}


with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
    routes = list(pool.map(route, points))
# Write only after every route has succeeded, preserving the previous complete snapshot on error.
(ROOT / 'route-data.js').write_text('/* Generated by scripts/update-routes.py; road estimates, not live navigation. */\nwindow.TRIP_ROUTES = ' + json.dumps(routes, ensure_ascii=False, separators=(',', ':')) + ';\n')
for i, item in enumerate(routes):
    print(f'Day {i+1}: {item["distance"]/1000:.1f} km, {item["duration"]/60:.0f} min (no traffic/weather buffer)')
